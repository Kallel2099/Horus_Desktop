package com.knowledge.horus.models;

public class DescarregarMod {

    private String codig;
    private String integ;
    private String humid;
    private String teste;
    private String selag;
    private String ident;

    public String getCodig() {
        return codig;
    }

    public void setCodig(String codig) {
        this.codig = codig;
    }

    public String getInteg() {
        return integ;
    }

    public void setInteg(String integ) {
        this.integ = integ;
    }

    public String getHumid() {
        return humid;
    }

    public void setHumid(String humid) {
        this.humid = humid;
    }

    public String getTeste() {
        return teste;
    }

    public void setTeste(String teste) {
        this.teste = teste;
    }

    public String getSelag() {
        return selag;
    }

    public void setSelag(String selag) {
        this.selag = selag;
    }

    public String getIdent() {
        return ident;
    }

    public void setIdent(String ident) {
        this.ident = ident;
    }
}
